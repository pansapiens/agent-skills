#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Inject UTF-8 meta tag, Hide/Show Labels toolbar, and clickable color-swatch
toggles into standalone HTML generated by molviewspec's molstar_html(ui="stories").
"""

import argparse
import logging
from pathlib import Path
import re
import sys

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
log = logging.getLogger(__name__)

LOAD_MARKER_RE = re.compile(
    r"mvsStories\.loadFromData\(mvsData,\s*\{\s*format:\s*'(?:mvsx|mvsj)'\s*\}\);"
)

INTERACTIVE_CSS = """
        #story-toolbar {
            display: flex; align-items: center; justify-content: space-between; gap: 10px;
            padding-bottom: 10px; border-bottom: 1px solid #d4d4d8;
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
            font-size: 12px; color: #4b5563; flex-shrink: 0;
        }
        #toggle-labels-btn {
            appearance: none; border: 1px solid #9ca3af; background: #fff; color: #111827;
            border-radius: 6px; padding: 5px 10px; font-size: 12px; font-weight: 600;
            cursor: pointer; white-space: nowrap;
        }
        #toggle-labels-btn.labels-off { background: #fee2e2; border-color: #ef4444; color: #991b1b; }
        #controls a:has(> span[style*="background-color"]) {
            text-decoration: none; display: inline-flex; align-items: center;
            vertical-align: middle; cursor: pointer; position: relative;
            padding: 1px; border-radius: 3px; transition: transform 0.12s;
        }
        #controls a:has(> span[style*="background-color"]):hover { transform: scale(1.22); }
        #controls a.swatch-hidden > span {
            opacity: 0.35; box-shadow: inset 0 0 0 1px rgba(17, 24, 39, 0.35);
        }
        #controls a.swatch-hidden::after {
            content: ""; position: absolute; left: -2px; right: -2px; top: 50%; height: 2px;
            background: #111827; box-shadow: 0 0 0 1px rgba(255, 255, 255, 0.9);
            transform: rotate(-45deg); pointer-events: none; border-radius: 1px;
        }
"""

INTERACTIVE_TOOLBAR = """
        <div id="story-toolbar">
            <button id="toggle-labels-btn" type="button">Hide Labels</button>
            <span>Click color squares to toggle &bull; Hover to highlight</span>
        </div>
"""

INTERACTIVE_JS = """
        (function setupStoryControls() {
            let labelsHidden = false;
            const hiddenRefs = new Set();
            let lastClickedAnchor = null;

            function getPlugin() {
                try {
                    const ctx = window.mvsStories && window.mvsStories.getContext();
                    return ctx?.state?.viewers?.value?.[0]?.model?.plugin || null;
                } catch (_) { return null; }
            }
            function setSubtreeHidden(plugin, rootRef, hide) {
                const state = plugin.state.data, queue = [rootRef];
                while (queue.length) {
                    const r = queue.shift();
                    if (!state.cells.has(r)) continue;
                    state.updateCellState(r, { isHidden: hide });
                    const kids = state.tree.children.get(r);
                    if (kids) kids.forEach(k => queue.push(k));
                }
            }
            function findCells(plugin, refs) {
                const mgr = plugin.managers?.markdownExtensions;
                return mgr?.findCells ? mgr.findCells(refs) : [];
            }
            function applyLabelsState(plugin) {
                for (const c of findCells(plugin, ['scene_labels'])) {
                    setSubtreeHidden(plugin, c.transform.ref, labelsHidden);
                }
            }
            function syncSwatches() {
                const root = document.getElementById('controls');
                if (!root) return;
                root.querySelectorAll('a').forEach(a => {
                    if (!a.querySelector('span[style*="background-color"]')) return;
                    if (!a.title) a.title = 'Click to show/hide in 3D • Hover to highlight';
                    const key = a.dataset.toggleKey;
                    if (key) {
                        const refs = key.split(',').map(s => s.trim()).filter(Boolean);
                        a.classList.toggle('swatch-hidden', refs.length > 0 && refs.every(r => hiddenRefs.has(r)));
                    }
                });
            }
            document.addEventListener('click', ev => {
                const a = ev.target?.closest?.('#controls a');
                if (a) lastClickedAnchor = a;
            }, true);

            function bind(plugin) {
                if (!plugin || plugin.__storyControlsBound) return;
                plugin.__storyControlsBound = true;
                plugin.managers.markdownExtensions.registerExtension({
                    name: 'toggle-refs',
                    execute: ({ event, args }) => {
                        if (event !== 'click' || !args['toggle-refs']) return;
                        const refs = String(args['toggle-refs']).split(',').map(s => s.trim()).filter(Boolean);
                        const cells = findCells(plugin, refs);
                        if (!cells.length) return;
                        const nextHidden = cells.some(c => !c.state.isHidden);
                        cells.forEach(c => setSubtreeHidden(plugin, c.transform.ref, nextHidden));
                        refs.forEach(r => nextHidden ? hiddenRefs.add(r) : hiddenRefs.delete(r));
                        if (lastClickedAnchor) {
                            lastClickedAnchor.dataset.toggleKey = refs.join(',');
                            const bg = lastClickedAnchor.querySelector('span')?.style?.backgroundColor;
                            if (bg) {
                                document.querySelectorAll('#controls a').forEach(a => {
                                    const sp = a.querySelector('span');
                                    if (sp && sp.style.backgroundColor === bg && !a.dataset.toggleKey) {
                                        a.dataset.toggleKey = refs.join(',');
                                    }
                                });
                            }
                        }
                        syncSwatches();
                    }
                });
                plugin.managers.snapshot.events.changed.subscribe(() => {
                    hiddenRefs.clear();
                    setTimeout(() => { applyLabelsState(plugin); syncSwatches(); }, 120);
                });
                const btn = document.getElementById('toggle-labels-btn');
                if (btn) {
                    btn.addEventListener('click', () => {
                        labelsHidden = !labelsHidden;
                        btn.textContent = labelsHidden ? 'Show Labels' : 'Hide Labels';
                        btn.classList.toggle('labels-off', labelsHidden);
                        applyLabelsState(plugin);
                    });
                }
                setTimeout(() => { applyLabelsState(plugin); syncSwatches(); }, 400);
            }
            const t = setInterval(() => { const p = getPlugin(); if (p) { bind(p); clearInterval(t); } }, 150);
        })();
"""


def inject_interactive_controls(html: str) -> str:
    """Return HTML with UTF-8 meta tag and interactive Mol* Story controls injected."""
    if 'id="story-toolbar"' in html:
        log.warning("Interactive controls already present; returning HTML unchanged.")
        return html

    missing = [m for m in ("</style>", '<div id="controls">') if m not in html]
    load_match = LOAD_MARKER_RE.search(html)
    if not load_match:
        missing.append("mvsStories.loadFromData(mvsData, { format: 'mvsx'|'mvsj' });")
    if missing:
        raise ValueError(
            f"Input HTML does not match expected molstar_html(ui='stories') layout; "
            f"missing marker(s): {', '.join(missing)}"
        )

    if "<meta charset=" not in html.lower():
        html = html.replace("<head>", '<head>\n    <meta charset="utf-8">', 1)
    html = html.replace("</style>", INTERACTIVE_CSS + "\n    </style>", 1)
    html = html.replace('<div id="controls">', '<div id="controls">' + INTERACTIVE_TOOLBAR, 1)
    load_stmt = load_match.group(0)
    html = html.replace(load_stmt, load_stmt + "\n" + INTERACTIVE_JS, 1)
    return html


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Inject interactive controls and UTF-8 charset into a Mol* Stories HTML file."
    )
    parser.add_argument("input_html", type=Path, help="Path to HTML file from mvs.molstar_html(ui='stories').")
    parser.add_argument(
        "-o",
        "--output",
        default=None,
        help="Output path (default: overwrite input_html in place; use '-' for stdout).",
    )
    args = parser.parse_args()

    if not args.input_html.is_file():
        log.error("Input file not found: %s", args.input_html)
        sys.exit(1)

    raw_html = args.input_html.read_text(encoding="utf-8")
    try:
        updated_html = inject_interactive_controls(raw_html)
    except ValueError as exc:
        log.error("%s", exc)
        sys.exit(1)

    if args.output == "-":
        sys.stdout.write(updated_html)
    else:
        dest = Path(args.output) if args.output else args.input_html
        dest.write_text(updated_html, encoding="utf-8")
        log.info("Wrote %s", dest)


if __name__ == "__main__":
    main()
